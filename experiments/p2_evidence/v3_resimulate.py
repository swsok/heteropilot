#!/usr/bin/env python
"""V3: re-simulate the chosen P2 and P3 candidates on their own, without the cache.

`WORK_ORDER_p2_regular_spec_evidence.md` STEP V3. Both chosen candidates are
`mix(...)` shapes, and D40 says `EnvelopeCache` keys on a placement string that
does not record WHICH island got which share -- so a candidate and its mirror
collapse to one entry and one of them is served the other's numbers (measured
8.5 % apart on TTFT for exactly this shape of A40 pair).

V3 compares a prediction against a measurement, so the prediction has to be the
candidate's own. **The cache is not used at all here**: `predict()` is called
directly, once per candidate, which makes a key collision impossible rather than
merely unlikely.

Everything else reproduces E-A1: the same cluster, the same service spec, the
same 300-request trace at seed 42, the same predictor settings. If the cached and
re-simulated values agree, the cached one was this candidate's; if they differ,
D40 fired on it and the re-simulated value is the one V3 must use.

Run:  .venv/bin/python experiments/p2_evidence/v3_resimulate.py
"""

from __future__ import annotations

import glob
import json
import sys
from dataclasses import asdict, is_dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from planner.candidate_generator import CandidateGenerator  # noqa: E402
from planner.inventory import (  # noqa: E402
    detect_islands,
    load_cluster_spec,
    load_profiles_for,
)
from planner.predictor.llmservingsim import LLMServingSimPredictor  # noqa: E402
from planner.spec import load_service_spec  # noqa: E402
from planner.util.workload import generate_trace  # noqa: E402

EA1 = REPO / "outputs/uncertainty/ea1/ea1_margin_modes.json"
CACHE = REPO / "outputs/uncertainty/ea1/cache"
WORK = REPO / "outputs/p2_evidence/v3_resim"
OUT = REPO / "experiments/p2_evidence/results/v3_resimulation.json"

#: The two the selection chose. P1 and P4 are single-island and D40-clean, so
#: they keep their cached predictions and are not re-run.
TARGETS = [
    ("P3", "mix(cuda-a40-node_a40a-tp1-dp1+cuda-a40-node_a40b-tp1-dp4)-s32-t2048"),
    ("P2", "mix(cuda-a40-node_a40a-tp2-dp1+cuda-a40-node_a40b-tp2-dp2)-s32-t8192"),
]

#: Metrics whose movement would change a verdict, so they are the ones compared.
COMPARED = ("p99_tpot_ms", "p99_ttft_ms", "p50_tpot_ms", "p95_tpot_ms",
            "served_concurrency", "throughput_tps", "total_energy_j",
            "tokens_per_joule")


def cached_metrics() -> dict[str, dict]:
    out = {}
    for path in glob.glob(str(CACHE / "*.json")):
        entry = json.loads(Path(path).read_text())
        if "candidate_id" in entry:
            out[entry["candidate_id"]] = entry.get("metrics", {})
    return out


def _metrics_of(result) -> dict:
    m = getattr(result, "metrics", None)
    if m is None:
        return {}
    return asdict(m) if is_dataclass(m) else dict(m)


def main() -> int:
    ea1 = json.loads(EA1.read_text())
    fixture = ea1["fixture"]

    spec = load_service_spec(fixture["service"])
    cluster = load_cluster_spec(fixture["cluster"])
    profiles = load_profiles_for(cluster, REPO)
    islands = detect_islands(cluster, profiles)
    by_id = {i.id: i for i in islands}

    WORK.mkdir(parents=True, exist_ok=True)
    trace = generate_trace(
        spec, WORK / "workload.jsonl",
        num_requests=fixture["num_requests"], seed=fixture["seed"],
    )
    predictor = LLMServingSimPredictor(
        trace, work_dir=WORK / "sims", timeout_s=900.0,
    )

    generated = CandidateGenerator(
        spec, cluster, islands, profiles, enable_prefix_caching=False,
    ).generate().candidates
    by_candidate_id = {c.id: c for c in generated}

    cached = cached_metrics()
    report = {"fixture": fixture, "cache_used": False, "candidates": []}

    for group, cid in TARGETS:
        candidate = by_candidate_id.get(cid)
        if candidate is None:
            print(f"!! {group} {cid}: not generated by the current generator")
            report["candidates"].append(
                {"group": group, "candidate_id": cid, "error": "not generated"})
            continue

        print(f"--- {group} {cid}", flush=True)
        result = predictor.predict(candidate, spec, cluster, by_id, profiles)
        fresh = _metrics_of(result)
        outcome = getattr(result.outcome, "name", str(result.outcome))
        print(f"    outcome={outcome}", flush=True)

        row = {"group": group, "candidate_id": cid, "outcome": outcome,
               "detail": getattr(result, "detail", ""), "comparison": {}}
        old = cached.get(cid, {})
        for key in COMPARED:
            a, b = old.get(key), fresh.get(key)
            delta_pct = None
            if isinstance(a, (int, float)) and isinstance(b, (int, float)) and a:
                delta_pct = (b - a) / a * 100.0
            row["comparison"][key] = {"cached": a, "resimulated": b,
                                      "delta_pct": delta_pct}
            if delta_pct is not None:
                print(f"    {key:22s} cached={a!s:>22} resim={b!s:>22} "
                      f"Δ={delta_pct:+.4f}%", flush=True)
        report["candidates"].append(row)

    OUT.write_text(json.dumps(report, indent=2, default=str) + "\n")
    print(f"\nwrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
